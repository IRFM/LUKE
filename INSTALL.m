Steps for building LUKE

========================================================
 STARTUP file
========================================================
1) Edit the file ~/LUKE/startup_LUKE.m
2) Run MatLab
3) Type "edit startup". 
	- If nothing append, the "startup.m" file doesnot exist. In this case, set the variable "luke_root" to the absolute path of LUKE. Save the file as ~/LUKE/startup.m and copy it in the user root directory of MatLab so that it is automatically recognized recognized by MatLab when it is launched.
	- if a "startup.m" file already exists, copy the lines 15 -> 17 from "~/LUKE/startup_LUKE.m" to the existing "startup.m" file (at the end for example), and set the variable "luke_root" to the absolute path of LUKE. Save the modified "startup.m" file
4) quit and relaunch MatLab
