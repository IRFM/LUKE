function [Sp0_imj,Sp0_ipj,Sm0_ijm,Sm0_ijp] = ...
    fluxes_dke_jd(df0dpn_imj,df0dpn_ipj,df0dmhu_imj,df0dmhu_ipj,f0_imj,f0_ipj,...
                  Dpp_imj,Dpp_ipj,Dpm_imj,Dpm_ipj,Fp_imj,Fp_ipj,lmmhu2,pnm,pnp,...
                  df0dmhu_ijm,df0dmhu_ijp,df0dpn_ijm,df0dpn_ijp,f0_ijm,f0_ijp,...
                  Dmm_ijm,Dmm_ijp,Dmp_ijm,Dmp_ijp,Fm_ijm,Fm_ijp,lmmhu2m,lmmhu2p,pn);
%
% by J. Decker. 12/03/02
%
% modified J.D. 07/02/03
%    
Sp0_imj = - Dpp_imj.*df0dpn_imj...
          + Dpm_imj.*sqrt(lmmhu2).*df0dmhu_imj./pnm...
          + Fp_imj.*f0_imj;
%
Sp0_ipj = - Dpp_ipj.*df0dpn_ipj...
          + Dpm_ipj.*sqrt(lmmhu2).*df0dmhu_ipj./pnp...
          + Fp_ipj.*f0_ipj;

%
if nargout > 2,
    %
    Sm0_ijm = Dmm_ijm.*sqrt(lmmhu2m).*df0dmhu_ijm./pn...
            - Dmp_ijm.*df0dpn_ijm...
            + Fm_ijm.*f0_ijm;
    %
    Sm0_ijp = Dmm_ijp.*sqrt(lmmhu2p).*df0dmhu_ijp./pn...
            - Dmp_ijp.*df0dpn_ijp...
            + Fm_ijp.*f0_ijp;
    %
end
