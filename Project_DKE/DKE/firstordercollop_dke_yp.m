function [I1,I2] = firstordercollop_dke_yp(f1,betath_ref,masku,maskl,dpn,xpn,xpn2,xpn3,xsigma,xgamma,xz,xz2,pn,pn2,pn3,sigma,gamma,z,z2,xJ1,xJ2,xJ3,xJ4,J1,J2,J3,J4,xTe_norm);
%
%First order correction of the Beliaev-Budker collision operator for accurate current drive calculations C(fM,fe). Describe the
%dampin of thermal electrons on the fast tail.
%
%by Y.Peysson CEA-DRFC <yves.peysson@cea.fr> and Joan Decker MIT-RLE (jodecker@mit.edu)
%
%
%
xf1 = f1'*ones(1,length(f1));
%
I1 = integral_dke_jd(dpn,xf1.*masku.*xpn3./xgamma,1)'/3/xTe_norm ...
      - integral_dke_jd(dpn,xf1.*masku.*xpn3,1)'.*gamma*2/3/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*masku.*xpn3.*xpn2./xgamma,1)'.*gamma/5/xTe_norm/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*masku.*(xgamma - xsigma./xz).*xpn./xgamma,1)' ...
      - integral_dke_jd(dpn,xf1.*masku.*xpn3.*xJ2./xgamma./xz2,1)'.*gamma/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*masku.*xpn3.*(1 + 3.0./xz2 - 3*xgamma.*xsigma./xz2./xz)./xgamma,1)'.*(gamma.*pn2 - 5*xTe_norm)/6/xTe_norm/xTe_norm ...   
      + integral_dke_jd(dpn,xf1.*masku.*xpn3.*xJ3./xz./xgamma,1)'.*gamma/2/betath_ref/betath_ref/xTe_norm/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*masku.*xpn3.*xJ1./xz2./xgamma,1)'.*gamma/2/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*masku.*xpn.*(xgamma.*xsigma./xz - 1)./xgamma,1)'.*pn2/xTe_norm ...
      - integral_dke_jd(dpn,xf1.*masku.*xpn3.*xJ4./xz./xgamma,1)'.*gamma/12/betath_ref/betath_ref/xTe_norm/xTe_norm;
I2 = integral_dke_jd(dpn,xf1.*maskl./xgamma,1)'/3/xTe_norm ...        
      + integral_dke_jd(dpn,xf1.*maskl,1)'.*(-2*gamma/3/xTe_norm + pn2/5/xTe_norm/xTe_norm) ...   
      + integral_dke_jd(dpn,xf1.*maskl./xgamma,1)'.*(gamma - sigma./z)./pn2 ...
      - integral_dke_jd(dpn,xf1.*maskl,1)'.*J2./z2/xTe_norm ...                 
      + integral_dke_jd(dpn,xf1.*maskl.*(xgamma.*xpn2 - 5*xTe_norm)./xgamma,1)'.*(1 + 3.0./z2 - 3*gamma.*sigma./z2./z)/6/xTe_norm/xTe_norm ...
      + integral_dke_jd(dpn,xf1.*maskl,1)'.*(J3./z/2/betath_ref/betath_ref/xTe_norm/xTe_norm + J1./z2/2/xTe_norm - J4./z/12/betath_ref/betath_ref/xTe_norm/xTe_norm) ...
      + integral_dke_jd(dpn,xf1.*maskl.*xpn2./xgamma,1)'.*(gamma.*sigma./z - 1)./pn2/xTe_norm;
