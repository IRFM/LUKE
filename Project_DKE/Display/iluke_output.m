function output = iluke_output(output)
%
if ~isfield(output,'data_proc'),
    %
    output.data_proc = proc_luke_jd(output,struct);
    %
end
%
flag_rf = output.data_proc.scalar.p0_rf_2piRp ~= 0;
%
output.info.txt = {...
        ['Total current       : ',num2str(output.data_proc.scalar.I_tot),' MA (positive for co-current)'],...
        ['Current peak r/a    : ',num2str(output.data_proc.scalar.jrhoT),' (square root of toroidal flux)'],...
        ['Current FWHM        : ',num2str(output.data_proc.scalar.jdrhoT),' (square root of toroidal flux)']};
if flag_rf,
    output.info.txt = [output.info.txt,...
        ['RF conv. param.    : ',num2str(output.data_proc.simul.residue_rf(end))]];
end
%
if isinf(output.data_proc.scalar.Rp),
    if flag_rf,
        output.info.txt = [output.info.txt,...
        ['Launched RF power   : ',num2str(output.data_proc.scalar.p0_rf_2piRp),' MW/m (P/2piRp)'],...
        ['Absorbed RF power   : ',num2str(output.data_proc.scalar.p_rf_2piRp),' MW/m ---> ',num2str(100*output.data_proc.scalar.p_rf_2piRp/output.data_proc.scalar.p0_rf_2piRp),' %. (P/2piRp)']];
        for in_rf = 1:length(output.data_proc.scalar.n_rf_list),
            output.info.txt = [output.info.txt,...
        ['RF power on harm. ',num2str(output.data_proc.scalar.n_rf_list(in_rf)),' : ',num2str(output.data_proc.scalar.np_rf_2piRp(in_rf)),' MW/m ---> ',num2str(100*output.data_proc.scalar.np_rf_2piRp(in_rf)/output.data_proc.scalar.p0_rf_2piRp),' %. (P/2piRp)']];
        end
        output.info.txt = [output.info.txt,...
        ['Linear RF power     : ',num2str(output.data_proc.scalar.p_rf_2piRp_lin),' MW/m ---> ',num2str(100*output.data_proc.scalar.p_rf_2piRp_lin/output.data_proc.scalar.p0_rf_2piRp),' %. (P/2piRp)']];
    end
    %
    output.info.txt = [output.info.txt,...
        ['Ohmic power         : ',num2str(output.data_proc.scalar.p_e_2piRp),' MW/m (P/2piRp)'],...
        ['Total power         : ',num2str(output.data_proc.scalar.p_tot_2piRp),' MW/m (P/2piRp)'],...
        ['CD efficiency       : ',num2str(output.data_proc.scalar.EtaRp),' A.m/W (I*Rp/P)']];
else
    if flag_rf,
        output.info.txt = [output.info.txt,...
        ['Launched RF power   : ',num2str(output.data_proc.scalar.p0_rf_2piRp*(2*pi*output.data_proc.scalar.Rp)),' MW'],...
        ['Absorbed RF power   : ',num2str(output.data_proc.scalar.p_rf_2piRp*(2*pi*output.data_proc.scalar.Rp)),' MW ---> ',num2str(100*output.data_proc.scalar.p_rf_2piRp/output.data_proc.scalar.p0_rf_2piRp),' %.']];
        for in_rf = 1:length(output.data_proc.scalar.n_rf_list),
            output.info.txt = [output.info.txt,...
        ['RF power on harm. ',num2str(output.data_proc.scalar.n_rf_list(in_rf)),' : ',num2str(output.data_proc.scalar.np_rf_2piRp(in_rf)*(2*pi*output.data_proc.scalar.Rp)),' MW ---> ',num2str(100*output.data_proc.scalar.np_rf_2piRp(in_rf)/output.data_proc.scalar.p0_rf_2piRp),' %.']];
        end
        output.info.txt = [output.info.txt,...
        ['Linear RF power     : ',num2str(output.data_proc.scalar.p_rf_2piRp_lin*(2*pi*output.data_proc.scalar.Rp)),' MW ---> ',num2str(100*output.data_proc.scalar.p_rf_2piRp_lin/output.data_proc.scalar.p0_rf_2piRp),' %.']];
    end
    %
    output.info.txt = [output.info.txt,...
        ['Ohmic power         : ',num2str(output.data_proc.scalar.p_e_2piRp*(2*pi*output.data_proc.scalar.Rp)),' MW'],...
        ['Total power         : ',num2str(output.data_proc.scalar.p_tot_2piRp*(2*pi*output.data_proc.scalar.Rp)),' MW'],...
        ['CD efficiency       : ',num2str(output.data_proc.scalar.EtaRp/output.data_proc.scalar.Rp),' A/W (I/P)']];
end
%
if flag_rf,
    output.info.txt = [output.info.txt,...
            ['RF efficiency       : ',num2str(output.data_proc.scalar.EtaRFRp),' 10^19 A/(W.m^2) (n_19*I*Rp/PRF)']];
end
