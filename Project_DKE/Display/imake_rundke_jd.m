function imake_rundke_jd(paths,fileids,status,rho_S,workdir,id_simul_o,opt_gui)
%
if nargin < 7,
	opt_gui = 1;
end
if nargin < 6,
	id_simul_o = '';
end
%
% This function automatically generates a rundke script to run LUKE
%
if ~isfield(fileids,'dkepath') || ~isfield(fileids,'dkeparam') || ~isfield(fileids,'equil'),
    disp('-----> the structures dkepath, dkeparam and equil must exist in a fileids to run LUKE.');
    return
end     
%
id_simul = input(['Please provide an id for the run [',id_simul_o,'] : '],'s');
if isempty(id_simul),
    id_simul = id_simul_o;
end
%
filestr = [workdir,'rundke_',id_simul];
filestr(filestr == '.') = 'p';
%
[data_file,data_path] = iputfile_jd(opt_gui,'rundke*.m','Please provide a fileids name for the LUKE run script',[filestr,'.m']);
%
if data_file == 0,
    disp('-----> No LUKE run script name specified.');
    return
end  
%
filename = [data_path,data_file];
%
% RUN SCRIPT GENERATION
%
s = {};
s = [s,{'% Script for running LUKE'}];
s = [s,{'%'}];
s = [s,{'% This script is automatically generated by irunluke_jd.'}];
s = [s,{'% by J. Decker (joan.decker@cea.fr) and Y. Peysson (yves.peysson@cea.fr)'}];
s = [s,{'%'}];
s = [s,{'clear all'}];
s = [s,{'clear mex'}];
s = [s,{'clear functions'}];
s = [s,{'close all'}];
s = [s,{'warning off'}];
s = [s,{'global nfig'}];
s = [s,{'pause(1)'}];
s = [s,{'%'}];
s = [s,{'p_opt = 2;'}];
s = [s,{'%'}];
s = [s,{'% *********************** Specify LUKE structures *****************************'}];
s = [s,{'%'}];
s = [s,{['id_simul = ''',id_simul,''';%Simulation ID']}];
s = [s,{['path_simul = '''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path']}];
s = [s,{'%'}];
s = [s,{'psin_S = [];%Normalized poloidal flux grid where calculations are performed (0 < psin_S < 1) (If one value: local calculation only, not used if empty)'}];
s = [s,{['rho_S = [',num2str(rho_S),'];%Normalized radial flux grid where calculations are performed (0 < rho_S < 1) (If one value: local calculation only, not used if empty)']}];
s = [s,{'%'}];
s = [s,{['id_dkepath = ''',fileids.dkepath,''';%For all paths used by DKE solver']}];
s = [s,{['path_dkepath = ''',paths.dkepath,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path']}];
s = [s,{'%'}];
s = [s,{['id_equil = ''',fileids.equil,''';%For plasma equilibrium']}];
s = [s,{['path_equil = ''',paths.equil,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path']}];
s = [s,{'%'}];
s = [s,{['id_dkeparam = ''',fileids.dkeparam,''';%For DKE code parameters']}];
s = [s,{['path_dkeparam = ''',paths.dkeparam,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path']}];
s = [s,{'%'}];
s = [s,{'id_dkedisplay = ''NO_DISPLAY'';%For output code display'}];
s = [s,{'path_dkedisplay = '''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'}];
s = [s,{'%'}];
s = [s,{'id_ohm = '''';%For Ohmic electric contribution'}];
s = [s,{'path_ohm = '''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'}];
%
if status.ohm,
    if ~isempty(fileids.ohm),
        disp(['----> The run script is generated with the ''ohm'' structure ',fileids.ohm,'.']); 
        s{end-1} = ['id_ohm = ''',fileids.ohm,''';%For Ohmic electric contribution'];
        s{end} = ['path_ohm = ''',paths.ohm,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'];
    else
        disp('----> The ''ohm'' structure was not saved and is not included in the run script.');
    end
else
    disp('----> The run script is generated without ''ohm'' structure.');
end
%
s = [s,{'%'}];
%
waves_idstr = '''';
waves_pathstr = '''';
cnt = 0;
if status.waves,
    for iw = 1:length(fileids.waves),
        if ~isempty(fileids.waves{iw}),
            disp(['----> The run script is generated with the ''wave'' structure ',fileids.waves{iw},'.']);
            if cnt > 0,
                waves_idstr = [waves_idstr,''',''',fileids.waves{iw}];
                waves_pathstr = [waves_pathstr,''',''',paths.waves{iw}];
            else
                waves_idstr = [waves_idstr,fileids.waves{iw}];
                waves_pathstr = [waves_pathstr,paths.waves{iw}];
                cnt = 1;
            end
        else
            disp(['----> The ''wave'' structure #',num2str(iw),'was not saved and is not included in the run script.']);
        end
    end
else
    disp('----> The run script is generated without ''wave'' structures.');
end
waves_idstr = [waves_idstr,''''];
waves_pathstr = [waves_pathstr,''''];
%
s = [s,{['ids_wave = {',waves_idstr,'};%For RF waves contribution (put all the type of waves needed)']}];
s = [s,{['paths_wave = {',waves_pathstr,'};%if nothing is specified, the working directory is first used and then MatLab is looking in all the path']}];
s = [s,{'%'}];
s = [s,{'id_transpfaste = '''';%For fast electron radial transport'}];
s = [s,{'path_transpfaste = '''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'}];
%
if status.transpfaste,
    if ~isempty(fileids.transpfaste),
        disp(['----> The run script is generated with the ''transpfaste'' structure ',fileids.transpfaste,'.']); 
        s{end-1} = ['id_transpfaste = ''',fileids.transpfaste,''';%For fast electron radial transport'];
        s{end} = ['path_transpfaste = ''',paths.transpfaste,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'];
    else
        disp('----> The ''transpfaste'' structure was not saved and is not included in the run script.');
    end
else
    disp('----> The run script is generated without ''transpfaste'' structure.');
end
%
s = [s,{'%'}];
s = [s,{'id_ripple = '''';%For fast electron magnetic ripple losses'}];
s = [s,{'path_ripple = '''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'}];
%
if status.ripple,
    if ~isempty(fileids.ripple),
        disp(['----> The run script is generated with the ''ripple'' structure ',fileids.ripple,'.']); 
        s{end-1} = ['id_ripple = ''',fileids.ripple,''';%For fast electron magnetic ripple losses'];
        s{end} = ['path_ripple = ''',paths.ripple,''';%if nothing is specified, the working directory is first used and then MatLab is looking in all the path'];
    else
        disp('----> The ''ripple'' structure was not saved and is not included in the run script.');
    end
else
    disp('----> The run script is generated without ''ripple'' structure.');
end
%
s = [s,{'%'}];
s = [s,{'[dkepath,equil,dkeparam,dkedisplay,ohm,waves,transpfaste,ripple] = load_structures_yp(''dkepath'',id_dkepath,path_dkepath,''equil'',id_equil,path_equil,''dkeparam'',id_dkeparam,path_dkeparam,''dkedisplay'',id_dkedisplay,path_dkedisplay,''ohm'',id_ohm,path_ohm,''waves'',ids_wave,paths_wave,''transpfaste'',id_transpfaste,path_transpfaste,''ripple'',id_ripple,path_ripple);'}];
s = [s,{'%'}];
s = [s,{'%************************************************************************************************************************************'}];
s = [s,{'%'}];
s = [s,{'[Znorm,Zcurr,ZP0,dke_out,radialDKE,equilDKE,momentumDKE,gridDKE,Zmomcoef,Zbouncecoef,Zmripple,mksa,XXsinksource] = run_lukert(id_simul,[],waves,psin_S,rho_S,dkepath,equil,dkeparam,dkedisplay,ohm,transpfaste,ripple,[],[],0);'}];
s = [s,{'%'}];	    
s = [s,{'%************************************************************************************************************************************'}];
s = [s,{'I_tot = sum(Zcurr.x_0_fsav.*equilDKE.xdA_dke*mksa.j_ref);'}];
s = [s,{'figure(''Name'',''Current profile''),'}];
s = [s,{'graph1D_jd(equilDKE.xrho,Zcurr.x_0_fsav*mksa.j_ref,0,0,''\rho'',''J_{tot} (MA/m^2)'',[''I_{tot} = '',num2str(I_tot),'' (MA)''],NaN,NaN,NaN,''-'',''none'',''r'',2,20,gca,0.9,0.7,0.7);drawnow'}];
s = [s,{'print_jd(p_opt,[id_simul,''_Curr'']);'}];
s = [s,{'%'}];
s = [s,{'PRF_tot = sum(ZP0.x_rf_fsav.*equilDKE.xdV_2piRp_dke(:)*mksa.P_ref*2*pi*equilDKE.Rp);'}];
s = [s,{'figure(''Name'',''LH Power''),'}];
s = [s,{'graph1D_jd(equilDKE.xrho,ZP0.x_rf_fsav*mksa.P_ref,0,0,''\rho'',''P_{RF} (MW/m^3)'',[''P_{RF} = '',num2str(PRF_tot),'' (MW)''],NaN,NaN,NaN,''-'',''none'',''r'',2,20,gca,0.9,0.7,0.7);drawnow'}];
s = [s,{'print_jd(p_opt,[id_simul,''_RF_Power'']);'}];
s = [s,{'%'}];
s = [s,{'POHM_tot = sum(ZP0.x_e_fsav.*equilDKE.xdV_2piRp_dke*mksa.P_ref*2*pi*equilDKE.Rp);'}];
s = [s,{'figure(''Name'',''Ohmic Power''),'}];
s = [s,{'graph1D_jd(equilDKE.xrho,ZP0.x_e_fsav*mksa.P_ref,0,0,''\rho'',''P_{OHM} (MW/m^3)'',[''P_{OHM} = '',num2str(POHM_tot),'' (MW)''],NaN,NaN,NaN,''-'',''none'',''r'',2,20,gca,0.9,0.7,0.7);drawnow'}];
s = [s,{'print_jd(p_opt,[id_simul,''_Ohm'']);'}];
s = [s,{'%'}];
s = [s,{'filename = [path_simul,''LUKE_RESULTS_'',id_equil,''_'',id_simul,''.mat''];'}];
s = [s,{'save(filename);'}];
s = [s,{'info_dke_yp(2,[''LUKE Results saved in '',filename]);'}];
s = [s,{'%'}];
%
fid = fopen(filename,'w');
%
for is = 1:length(s),
    fprintf(fid,'%s\n',s{is});
end
%
fclose(fid);
disp(['-----> The rundke fileids ',filename,' has been created.']);
%


