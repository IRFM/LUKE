function imake_makeexternal_TCV_jd(workdir,external,opt_gui)
%
if nargin < 3,
	opt_gui = 1;
end
%
% This function automatically generates a make_external_TCV script to generate external structures
%
externalstr = external.id;
externalstr(externalstr == '.') = 'p';
%
[data_file,data_path] = iputfile_jd(opt_gui,'make_external_TCV*.m','Please provide a name for the make_external script',[workdir,'make_external_',externalstr,'.m']);
%
if data_file == 0,
    disp('-----> No make_external script name specified.');
    return
end  
%
filename = [data_path,data_file];
%
basestr = 'TCV';
%
shotnum = external.equil.shotnum;
shotime = external.equil.shotime;
%
it1 = length([basestr,'_',shotnum,'_',shotime,'_']) + 1;
it2 = it1 - 1 + strfind(external.id(it1:end),'_');
%
t1 = external.id(it1:it2(1) - 1);
t2 = external.id(it2(1) + 1:it2(2) - 1);
%
launchstr = external.id(it2(2) + 2:end);
itL = strfind(launchstr,'_');
%
laun = '[';
%
for iL = 1:length(itL)-1,
    laun = [laun,launchstr(itL(iL) + 1:itL(iL+1) - 1),','];
end
laun = [laun,launchstr(itL(end) + 1:end),']'];
%
f_opt = external.equil.prof.teflag;
%
% RUN SCRIPT GENERATION
%
s = {};
s = [s,{'% Script for generating external structure from TCV database'}];
s = [s,{'%'}];
s = [s,{'% This script is automatically generated by imake_makeexternal-TCV_jd.'}];
s = [s,{'% by J. Decker (joan.decker@cea.fr) and Y. Peysson (yves.peysson@cea.fr)'}];
s = [s,{'%'}];
s = [s,{'clear all'}];
s = [s,{'clear mex'}];
s = [s,{'clear functions'}];
s = [s,{'close all'}];
s = [s,{'%'}];
s = [s,{['basestr = ''',basestr,''';']}];
s = [s,{'%'}];
s = [s,{['workdir = ''',workdir,''';']}];
s = [s,{'%'}];
s = [s,{['shotnum = ',shotnum,';%shot number']}];
s = [s,{['shotime = ',num2str(str2num(shotime)),';%shot time']}];
s = [s,{'%'}];
s = [s,{['t1 = ',t1,';% initial time for data averaging']}];
s = [s,{['t2 = ',t2,';% final time for data averaging']}];
s = [s,{'%'}];
s = [s,{['laun = ',laun,';%Vector of EC launchers to account for (ex: [1,3])']}];
s = [s,{'%'}];
s = [s,{['f_opt = ',num2str(f_opt),';% (0) load Te from fitted Thomson only, (1) load Te with Xte renormalization']}];
s = [s,{'%'}];
s = [s,{'l_opt = 1;% Option for liuqe version (1,2,3)'}];
s = [s,{'%'}];
s = [s,{'% ------------------------------------------------------------------------------------'}];
s = [s,{'%'}];
s = [s,{'shotnumstr = num2str(shotnum);'}];
s = [s,{'shotimestr = num2str(shotime,''%6.4f'');'}];
s = [s,{'%'}];
s = [s,{'eqdsk_path = [workdir,''/''];'}];
s = [s,{'%'}];
s = [s,{'eqdsk_file = [''eqdsk.'',shotnumstr,''t'',shotimestr];'}];
s = [s,{'%'}];
s = [s,{'data_path = [workdir,''/''];'}];
s = [s,{'%'}];
s = [s,{'data_str = [''data_'',basestr,''_'',shotnumstr,''_'',num2str(t1),''_'',num2str(t2)];'}];
s = [s,{'%'}];
s = [s,{'if ~exist(''make_eqdsk.m'',''file''),'}];
s = [s,{'    disp(''-----> Access to the TCV database is not granted.'');'}];
s = [s,{'    disp(''-----> You need the file make_eqdsk.m in the matlab path.'');'}];
s = [s,{'    return;'}];
s = [s,{'end'}];
s = [s,{'%'}];
s = [s,{'if ~exist(''collect_parameters_for_luke.m'',''file''),'}];
s = [s,{'    disp(''-----> Access to the TCV database is not granted.'');'}];
s = [s,{'    disp(''-----> You need the file collect_parameters_for_luke.m in the matlab path.'');'}];
s = [s,{'    return;'}];
s = [s,{'end'}];
s = [s,{'%'}];
s = [s,{['make_eqdsk(shotnum,shotime,workdir,''',basestr,''',l_opt);%call LIUQUE']}];
s = [s,{'%'}];
s = [s,{'launstr = '''';'}];
s = [s,{'for il = 1:length(laun),'}];
s = [s,{'    launstr = [launstr,''_'',num2str(laun(il))];'}];
s = [s,{'end'}];
s = [s,{'%'}];
s = [s,{'data_path = [workdir,''/''];'}];
s = [s,{'data_file = [data_str,launstr,''.mat''];'}];
s = [s,{'%'}];
s = [s,{'collect_parameters_for_luke(shotnum,t1,t2,laun,[data_path,data_file],f_opt);%load dhot parameters'}];
s = [s,{'%'}];
s = [s,{'% ------------------------------------------------------------------------------------'}];
s = [s,{'%'}];
s = [s,{'% return structure equil'}];
s = [s,{'%'}];
s = [s,{'external.equil.shotnum = shotnumstr;'}];
s = [s,{'external.equil.shotime = shotimestr;'}];
s = [s,{'external.equil.magnetic.eqdsk_path = eqdsk_path;'}];
s = [s,{'external.equil.magnetic.eqdsk_file = eqdsk_file;'}];
s = [s,{'%'}];
s = [s,{'external.equil.prof = load([data_path,data_file],''shot'',''rho'',''ne'',''te'',''ti'',''zeff'',''zaxis'',''btsign'',''ipsign'',''teflag'');'}];
s = [s,{'external.equil.prof.data_path = data_path;'}];
s = [s,{'external.equil.prof.data_file = data_file;'}];
s = [s,{'external.wave = load([data_path,data_file],''shot'',''laun'',''angles*'');'}];
s = [s,{'external.ohm = load([data_path,data_file],''shot'',''vloop'');'}];
s = [s,{'%'}];
s = [s,{'external.id = [''TCV_'',shotnumstr,''_'',shotimestr,''_'',num2str(t1),''_'',num2str(t2),''_L'',launstr];'}];
s = [s,{'%'}];
s = [s,{'save_str = [''EXTERNAL_'',external.id,''.mat''];'}];
s = [s,{'eval([''save '',save_str,'' external'']);'}];
s = [s,{'%'}];
s = [s,{'info_dke_yp(2,''External parameters saved'');'}];
s = [s,{'%'}];
%
fid = fopen(filename,'w');
%
for is = 1:length(s),
    fprintf(fid,'%s\n',s{is});
end
%
fclose(fid);
disp(['-----> The make_external script ',filename,' has been created.']);
%

