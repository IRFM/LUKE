function equil = makeEquilFromLuke(equil_luke,rho_star)
% the argument rho_star is optional and should normally not be set manually

% id
equil.id = equil_luke.id;

% Data processing of LUKE equilibrium
Ra = equil_luke.ptx(end,:);
Za = equil_luke.pty(end,:);
Rp = equil_luke.Rp;
if Rp == inf % cylindrical case
    Rp = 1e4;
end
Zp = equil_luke.Zp;

% Plasma boundary
equil.R0_a = Rp + (min(Ra)+max(Ra))/2;
equil.Z0_a = Zp;
[~,ind_pi] = min(abs(equil_luke.theta-pi)); % indice of theta = pi
equil.a = (max(Ra)-Ra(ind_pi))/2; % remark : ap = max(Ra)-Rp = R(rho=rho_max,theta=0)-Rp != a
points = cat(1,Ra+Rp,Za+Zp);
equil.boundary = cat(2,equil.R0_a,equil.Z0_a,equil.a,reshape(points,1,numel(points)));

% Value of rho_star if specified
if nargin>1
    equil.rho_star = rho_star;
%elseif isfield(equil_luke,'ludwig') && isfield(equil_luke.ludwig,'rho_star')
%    equil.rho_star = equil_luke.ludwig.rho_star;
end

% Magnetic field at the geometric center {R0_a,Z0_a}
% WARNING: B0 should be the external toroidal magnetic field at the center,
% (ie the field created by the toroidal field coils only
% Below, we take the total toroidal magnetic field (generated by TF coils 
% + plasma) which induces a small error
distance_to_R0a = (equil_luke.ptx+Rp-equil.R0_a).^2 + (equil_luke.pty+Zp-equil.Z0_a).^2 ;
[~,i_R0a] = min(distance_to_R0a,[],'all','linear') ; % index of the geometric center in the matrix
equil.B0 = equil_luke.ptBPHI(i_R0a); % minus sign because zeta (direction of B0) is opposed to phi

% List of rhos in Ludwig's definition
equil.rhos = (equil_luke.ptx(:,1)-equil_luke.ptx(:,ind_pi))./2;
if size(equil.rhos,1)==1
    equil.rhos = equil.rhos';
end

% Electron temperature profile
equil.temperature.electron.profile = equil_luke.pTe'; % in keV
equil.temperature.electron.derivative_profile = gradient(equil_luke.pTe,equil.rhos')';

% Ion temperature profile
equil.temperature.ion.profile = equil_luke.pzTi'; % in keV
equil.temperature.ion.derivative_profile = gradient(equil_luke.pzTi,equil.rhos',1)';

% Electron density profile
equil.density.electron.profile = equil_luke.pne';
equil.density.electron.derivative_profile = gradient(equil_luke.pne,equil.rhos')';

% Ion density profile
equil.density.ion.profile = equil_luke.pzni';
equil.density.ion.derivative_profile = gradient(equil_luke.pzni,equil.rhos',1)';

% ion composition of the plasma (not necessary)
if isfield(equil_luke,'zZi')
    equil.zZi = equil_luke.zZi;
end
if isfield(equil_luke,'zmi')
    equil.zmi = equil_luke.zmi;
end

% Toroidal current profile
psin = equil_luke.psi_apRp/equil_luke.psi_apRp(end);
rhos_luke = psi2rho_jd(equil_luke,psin)'; % rhos of equil_luke
if size(rhos_luke,1)==1
    rhos_luke = rhos_luke';
end
thetas_luke = 0:pi/50:2*pi;
equil_fit = fitequil_yp(equil_luke);
equil_val = equilval_yp(equil_fit,rhos_luke,thetas_luke);
equil.current.IT.profile = Iphi_luke(rhos_luke,thetas_luke,equil_val); % size n*1 ; minus sign because phi is opposed to zeta
equil.current.IT.derivative_profile = gradient(equil.current.IT.profile,equil.rhos);
equil.current.IT.IT_a = equil.current.IT.profile(end);

% value of rho_star if not specified
if ~isfield(equil,'rho_star')
    [rho_star,has_converged] = optimizeMatchingRadius(equil);
    if has_converged
        equil.rho_star = rho_star;
    else
        equil.rho_star = 0.7*a ; % arbitrary default value for rho_star
        warning('No maximum in rho_star has been found for the internal energy, a default value is taken. Therefore, the computed solution will not be reliable.');
    end
end

end